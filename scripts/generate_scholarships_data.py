def main():
    data_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "data"))
    out_file = os.path.join(data_dir, "scholarships.json")

    print(f"Total schemes compiled: {len(SCHEMES)}")
    ids = set()
    for s in SCHEMES:
        assert s["id"] not in ids, f"Duplicate ID: {s['id']}"
        ids.add(s["id"])
        assert s["apply_url"].startswith("https://"), f"Non-HTTPS apply_url in {s['id']}"
        assert s["source_url"].startswith("https://"), f"Non-HTTPS source_url in {s['id']}"
        assert s["portal_url"].startswith("https://"), f"Non-HTTPS portal_url in {s['id']}"

    with open(out_file, "w", encoding="utf-8") as f:
        json.dump(SCHEMES, f, indent=2, ensure_ascii=False)

    print(f"Successfully saved {len(SCHEMES)} schemes to {out_file}")

if __name__ == "__main__":
    main()
