def build_full_database():
    all_schemes = list(BASE_SCHEMES) + list(ADDITIONAL_SCHEMES)
    seen_ids = set()
    deduped = []
    for s in all_schemes:
        sid = s["id"]
        if sid in seen_ids:
            continue
        seen_ids.add(sid)
        # Verify mandatory keys
        assert "apply_url" in s and s["apply_url"].startswith("https://"), f"Missing or invalid apply_url in {sid}"
        assert "source_url" in s and s["source_url"].startswith("https://"), f"Missing or invalid source_url in {sid}"
        assert "portal_url" in s and s["portal_url"].startswith("https://"), f"Missing or invalid portal_url in {sid}"
        assert "deadline" in s, f"Missing deadline in {sid}"
        assert "last_verified" in s, f"Missing last_verified in {sid}"
        assert "verified" in s, f"Missing verified in {sid}"
        deduped.append(s)

    project_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    out_path = os.path.join(project_root, "data", "scholarships.json")

    with open(out_path, "w", encoding="utf-8") as f:
        json.dump(deduped, f, indent=2, ensure_ascii=False)

    print(f"Successfully generated full database with {len(deduped)} scholarships at {out_path}")
    return deduped

if __name__ == "__main__":
    build_full_database()
